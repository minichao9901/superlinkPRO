import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {SourceStore} from '../../web/app/shared/dbg/source.js';
import {readReferencedSources,sourceBatches} from '../../web/app/source-snapshot.js';

test('shared SourceStore resolves full suffixes and refuses ambiguous basenames without reading contents',async()=>{
  let reads=0;
  const files=['project/sdk/Core/Src/main.c','project/other/Src/main.c','project/a/common.h','project/b/common.h'].map(name=>({name:path.basename(name),webkitRelativePath:name,size:20,text:async()=>{reads++;return name;}}));
  const store=new SourceStore();await store.setExpectedPaths(['E:/build/sdk/Core/Src/main.c','E:/build/common.h']);store.indexFileList(files);
  assert.equal(reads,0);assert.equal(await store.read('E:/build/sdk/Core/Src/main.c'),files[0].webkitRelativePath);
  await assert.rejects(store.read('E:/build/common.h'),/找不到/);assert.equal(reads,1);
});
test('actual SDK plus 5000 unrelated paths matches ELF sources without reading unrelated files',async()=>{
  const root=path.resolve('firmware/stm32h7b0_spi_trace'),files=[];
  async function walk(folder){for(const entry of await fs.readdir(folder,{withFileTypes:true})){const file=path.join(folder,entry.name);if(entry.isDirectory())await walk(file);else files.push({name:entry.name,webkitRelativePath:'stm32h7b0_spi_trace/'+path.relative(root,file).replaceAll('\\','/'),path:file});}}
  await walk(root);
  // Manifest represents real compile paths from this sealed ELF; generated by the server test separately.
  const refs=['E:/web-etm-trace/firmware/stm32h7b0_spi_trace/sdk/Core/Src/main.c','E:/web-etm-trace/firmware/stm32h7b0_spi_trace/sdk/Drivers/STM32H7xx_HAL_Driver/Src/stm32h7xx_hal_spi.c'];
  let reads=0;for(const f of files){f.size=(await fs.stat(f.path)).size;f.text=async()=>{reads++;return fs.readFile(f.path,'utf8');};}
  for(let i=0;i<5000;i++)files.push({name:'unused-'+i+'.h',webkitRelativePath:'stm32h7b0_spi_trace/sdk/unrelated/unused-'+i+'.h',size:10,text:async()=>{throw Error('unrelated source must not be read');}});
  const store=new SourceStore();await store.setExpectedPaths(refs);store.indexFileList(files);assert.equal(reads,0);
  const result=await readReferencedSources(store,refs);assert.equal(Object.keys(result.sources).length,2);assert.equal(result.failed.length,0);assert.equal(reads,2);assert.ok(files.length>3000);
});
test('UTF-8/JSON escaping is included in batch sizing',()=>{
  const batches=sourceBatches({'a.c':'中文\n'.repeat(5),'b.c':'中文\n'.repeat(5)},70);
  assert.equal(batches.length,2);assert.deepEqual(Object.assign({},...batches),{'a.c':'中文\n'.repeat(5),'b.c':'中文\n'.repeat(5)});
});

test('directory handles open only ELF paths instead of traversing the full SDK',async()=>{
  const store=new SourceStore();let opened=0,reads=0;
  const root={getDirectoryHandle:async()=>root,getFileHandle:async()=>{opened++;return {getFile:async()=>({size:12,text:async()=>{reads++;return 'source text';}})};},entries:()=>{throw Error('不应遍历整棵目录');}};
  store.root=root;store.rootName='sdk';await store.setExpectedPaths(['E:/sdk/Core/Src/main.c','E:/sdk/Drivers/spi.c']);
  assert.equal(opened,2);assert.equal(reads,0);const result=await readReferencedSources(store,store.expected);assert.equal(reads,2);assert.equal(result.failed.length,0);
});
test('SourceStore file limits and read cache match debug/SWO',async()=>{
  const store=new SourceStore();let reads=0;
  store.indexFileList([{name:'small.c',size:5,text:async()=>{reads++;return 'code';}},{name:'large.c',size:3*1024*1024,text:async()=>{throw Error('不应读取过大源码');}}]);
  assert.equal(await store.read('small.c'),'code');assert.equal(await store.read('small.c'),'code');assert.equal(reads,1);await assert.rejects(store.read('large.c'),/太大不读/);
});
